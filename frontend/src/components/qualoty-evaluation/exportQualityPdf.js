import { jsPDF } from 'jspdf'

export function buildQualityPdf(report) {
  const doc = new jsPDF({ unit: 'mm', format: 'a4' })
  const margin = 18
  const width = 174
  let y = 34
  const percent = (value) => value == null ? 'Not applicable' : `${value}%`
  const clean = (value) => String(value ?? '').replace(/[\u2010-\u2015]/g, '-').replace(/[\u2018\u2019]/g, "'").replace(/[\u201c\u201d]/g, '"')
  function header() {
    doc.setFillColor(52, 120, 246)
    doc.roundedRect(margin, 12, 7, 7, 2, 2, 'F')
    doc.setFont('helvetica', 'bold'); doc.setFontSize(10); doc.setTextColor(40, 35, 65)
    doc.text('DesignTrace AI', margin + 10, 17)
    doc.setDrawColor(222, 220, 235); doc.line(margin, 23, 192, 23)
  }
  function room(height) {
    if (y + height > 277) { doc.addPage(); header(); y = 34 }
  }
  function text(value, { size = 10, bold = false, color = [65, 61, 80], gap = 3 } = {}) {
    doc.setFont('helvetica', bold ? 'bold' : 'normal'); doc.setFontSize(size)
    const lines = doc.splitTextToSize(clean(value), width)
    const step = size * 0.48
    for (const line of lines) {
      room(step)
      doc.setFont('helvetica', bold ? 'bold' : 'normal'); doc.setFontSize(size); doc.setTextColor(...color)
      doc.text(line, margin, y); y += step
    }
    y += gap
  }
  function section(title) {
    room(22); y += 3
    text(title, { size: 13, bold: true, color: [88, 70, 175], gap: 5 })
  }
  header()
  doc.setProperties({ title: `Quality Evaluation - ${report.project_id}`, author: 'DesignTrace AI', subject: report.evaluation_id })
  text('Quality Evaluation Report', { size: 22, bold: true, color: [32, 28, 50], gap: 6 })
  text(`Project: ${report.project_id}`)
  text(`Evaluation: ${report.evaluation_id}`)
  text(`Generated: ${report.generated_at}`)
  const m = report.metrics
  const urgent = report.findings.filter((f) => ['CRITICAL', 'HIGH'].includes(f.severity)).length
  section('Executive summary')
  const summary = m.total_applicable_rules === 0
    ? 'No rules were applicable to the supplied design. This report does not establish design quality.'
    : `${m.passed_rules} of ${m.total_applicable_rules} applicable checks passed; ${m.failed_rules} failed and ${m.skipped_rules} were skipped. ${report.findings.length} finding(s) were recorded, including ${urgent} high or critical finding(s).`
  text(summary)
  if (m.skipped_rules) text('Evaluation is incomplete: skipped checks are unresolved and must not be treated as passes.', { bold: true, color: [145, 90, 15] })
  text(urgent ? 'Priority: address high and critical findings first, then review the remaining findings and skipped checks.' : report.findings.length ? 'Priority: review the recommendations and resolve the recorded findings.' : m.skipped_rules ? 'Priority: review skipped-check rationales and supply missing evidence or retry unavailable providers.' : m.total_applicable_rules ? 'No failures were recorded in the evaluated scope. This is a design review, not a runtime security certification.' : 'Supply relevant requirements and design artifacts before evaluating again.')

  const cards = [
    ['QUALITY PASS RATE', percent(m.quality_pass_percentage)],
    ['NFR COVERAGE', percent(m.nfr_coverage_percentage)],
    ['HIGH / CRITICAL', String(urgent)],
  ]
  room(28)
  cards.forEach(([label, value], index) => {
    const x = margin + index * 59
    doc.setFillColor(244, 245, 251); doc.roundedRect(x, y, 56, 24, 2, 2, 'F')
    doc.setFont('helvetica', 'bold'); doc.setFontSize(8); doc.setTextColor(90, 85, 110); doc.text(label, x + 4, y + 7)
    doc.setFontSize(value === 'Not applicable' ? 12 : 18); doc.setTextColor(40, 35, 65); doc.text(value, x + 4, y + 18)
  })
  y += 32
  section('Check outcomes')
  const outcomes = [
    ['Passed', m.passed_rules, [30, 133, 102]],
    ['Failed', m.failed_rules, [195, 64, 78]],
    ['Skipped', m.skipped_rules, [183, 126, 30]],
  ]
  outcomes.forEach(([label, count, color]) => {
    room(12)
    doc.setFont('helvetica', 'normal'); doc.setFontSize(10); doc.setTextColor(65, 61, 80)
    doc.text(label, margin, y + 5)
    doc.setFillColor(237, 239, 245); doc.rect(margin + 28, y, 115, 7, 'F')
    if (m.total_applicable_rules > 0 && count > 0) {
      doc.setFillColor(...color); doc.rect(margin + 28, y, 115 * count / m.total_applicable_rules, 7, 'F')
    }
    doc.text(String(count), 188, y + 5, { align: 'right' }); y += 12
  })
  text('Bar lengths show each outcome as a share of all applicable checks.', { size: 8 })
  section('How to read these metrics')
  text('Quality pass rate = passed checks / all applicable checks. Skipped checks remain in the denominator. N/A means there were no applicable checks.', { size: 9 })
  text(`NFR coverage: ${m.evaluated_nfrs} of ${m.applicable_nfrs} applicable NFRs were evaluated. Coverage measures assessment coverage, not whether requirements passed.`, { size: 9 })
  text('Report layout and metrics are generated by application code. Semantic assessments may be supplied by an LLM; deterministic checks run in backend code.', { size: 9 })

  doc.addPage(); header(); y = 34
  section('NFR category results')
  text('Compare applicable checks by category. Zero applicable checks are shown as N/A.', { size: 9 })
  const columns = [margin, 67, 92, 114, 136, 160, 192]
  function tableHeader() {
    doc.setFillColor(47, 42, 76); doc.rect(margin, y, width, 10, 'F')
    doc.setFont('helvetica', 'bold'); doc.setFontSize(8); doc.setTextColor(255, 255, 255)
    ;['Category', 'Applicable', 'Passed', 'Failed', 'Skipped', 'Pass rate'].forEach((label, i) => doc.text(label, columns[i] + 2, y + 6))
    y += 10
  }
  tableHeader()
  m.category_summaries.forEach((c, index) => {
    doc.setFont('helvetica', 'normal'); doc.setFontSize(9)
    const lines = doc.splitTextToSize(clean(c.category), 44)
    const height = Math.max(12, lines.length * 4.5 + 5)
    if (y + height > 273) { doc.addPage(); header(); y = 34; tableHeader() }
    doc.setFillColor(...(index % 2 ? [255, 255, 255] : [245, 246, 251])); doc.rect(margin, y, width, height, 'F')
    doc.setFont('helvetica', 'normal'); doc.setFontSize(9); doc.setTextColor(65, 61, 80)
    doc.text(lines, margin + 2, y + 6)
    ;[c.applicable_rules, c.passed_rules, c.failed_rules, c.skipped_rules, c.pass_percentage == null ? 'N/A' : `${c.pass_percentage}%`].forEach((value, i) => doc.text(String(value), columns[i + 1] + 2, y + 6))
    y += height
  })
  y += 7
  section('Findings by severity')
  const severities = ['CRITICAL', 'HIGH', 'MEDIUM', 'LOW']
  severities.forEach((severity) => {
    const count = report.findings.filter((f) => f.severity === severity).length
    text(`${severity}: ${count}`, { size: 9, gap: 1 })
  })
  doc.addPage(); header(); y = 34
  section('Findings and recommendations')
  if (!report.findings.length) text('No findings were returned by this evaluation.')
  const priority = { CRITICAL: 4, HIGH: 3, MEDIUM: 2, LOW: 1 }
  const orderedFindings = [...report.findings].sort((a, b) => priority[b.severity] - priority[a.severity])
  for (const [index, f] of orderedFindings.entries()) {
    room(25)
    text(`${index + 1}. ${f.rule_id} | ${f.severity} | ${f.quality_attribute}`, { bold: true })
    text(f.rationale)
    text(`Artifact: ${f.artifact_type}. Check: ${f.check_type}. NFRs: ${f.affected_nfr_ids.join(', ') || 'None linked'}.`, { size: 9 })
    text('Evidence', { bold: true })
    for (const evidence of f.evidence) text(`- ${evidence}`, { size: 9 })
    if (!f.evidence.length) text('No evidence supplied.', { size: 9 })
    text(`Recommendation: ${f.recommendation}`)
  }
  if (report.finding_groups?.length) {
    section('Related findings')
    for (const g of report.finding_groups) {
      room(20); text(`${g.title} | ${g.severity}`, { bold: true }); text(g.summary)
      text(`Rules: ${g.rule_ids.join(', ')}`, { size: 9 })
      for (const recommendation of g.recommendations) text(`- ${recommendation}`)
    }
  }
  section('Rule evaluation details')
  if (!report.rule_results.length) text('No rules were applicable.')
  for (const r of report.rule_results) {
    room(20); text(`${r.rule_id} | ${r.status} | ${r.check_type}`, { bold: true })
    text(r.rationale)
    if (r.provider) text(`Provider: ${r.provider}`, { size: 9 })
  }
  const pages = doc.getNumberOfPages()
  for (let page = 1; page <= pages; page++) {
    doc.setPage(page); doc.setDrawColor(222, 220, 235); doc.line(margin, 283, 192, 283)
    doc.setFont('helvetica', 'normal'); doc.setFontSize(8); doc.setTextColor(110, 105, 125)
    doc.text('DesignTrace AI | Quality Evaluation', margin, 289)
    doc.text(`${page} / ${pages}`, 192, 289, { align: 'right' })
  }
  return doc
}

export function exportQualityPdf(report) {
  buildQualityPdf(report).save(`${report.evaluation_id.replace(/[^a-zA-Z0-9_-]/g, '_')}.pdf`)
}
