def validate(records_to_validate):
    assert len(records_to_validate) == 80

    positive = sum(
        int(item["label"])
        for item in records_to_validate
    )

    negative = len(records_to_validate) - positive

    assert positive == 40
    assert negative == 40

    source_counts = {}

    for item in records_to_validate:
        source = item["source_module"]
        source_counts[source] = source_counts.get(source, 0) + 1

    expected_sources = {
        "architecture_decision": 20,
        "database_design": 20,
        "api_component_design": 20,
        "quality_evaluation": 20,
    }

    assert source_counts == expected_sources

    ids = [
        item["decision_id"]
        for item in records_to_validate
    ]

    assert len(ids) == len(set(ids))

    families = [
        item["scenario_family"]
        for item in records_to_validate
    ]

    assert len(families) == len(set(families))


def write_dataset():
    validate(records)

    OUTPUT_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    with OUTPUT_FILE.open(
        "w",
        encoding="utf-8",
        newline="",
    ) as file:
        writer = csv.DictWriter(
            file,
            fieldnames=FIELDNAMES,
        )

        writer.writeheader()
        writer.writerows(records)

    print()
    print("ADR Hard Challenge Dataset")
    print("==========================")
    print(f"Output: {OUTPUT_FILE}")
    print(f"Total records: {len(records)}")

    positive = sum(
        int(item["label"])
        for item in records
    )

    print(f"Significant: {positive}")
    print(
        f"Non-significant: "
        f"{len(records) - positive}"
    )

    print()
    print("Source distribution")

    for source in [
        "architecture_decision",
        "database_design",
        "api_component_design",
        "quality_evaluation",
    ]:
        count = sum(
            1
            for item in records
            if item["source_module"] == source
        )

        print(
            f"{source}: {count}"
        )

    print()
    print(
        "Hard challenge dataset validation PASSED"
    )


