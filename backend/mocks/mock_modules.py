def execute_mock_module(
    module_name,
    project,
    approved_outputs,
    version=1,
    module_input=None,
):
    """
    Execute a deterministic PP1 mock Module.

    Structured inputs are checked, but results remain
    fixed Library Management examples.
    """

    if module_name not in MOCK_OUTPUTS:
        raise ValueError(
            f"Unknown mock Module: {module_name}"
        )

    if not isinstance(module_input, dict):
        raise ValueError(
            f"{module_name}: structured input required."
        )

    if module_input.get("project_id") != project.project_id:
        raise ValueError(
            f"{module_name}: project ID mismatch."
        )

    output = deepcopy(MOCK_OUTPUTS[module_name])

    if module_name == "requirement_analysis":
        required_fields = (
            "raw_description",
            "project_context",
        )

        for field in required_fields:
            if field not in module_input:
                raise ValueError(
                    f"Missing Requirement Analysis input: {field}"
                )

        description = module_input["raw_description"]

        if not isinstance(description, str) or not description.strip():
            raise ValueError(
                "Requirement Analysis description is required."
            )

        if not isinstance(
            module_input["project_context"], dict
        ):
            raise ValueError(
                "project_context must be a dictionary."
            )

        output["input_summary"] = {
            "project_id": module_input["project_id"],
            "description_received": description,
            "project_context_received": deepcopy(
                module_input["project_context"]
            ),
        }

    else:
        received = module_input.get(
            "approved_upstream_outputs"
        )

        required = MODULE_DEPENDENCIES[module_name]

        if not isinstance(received, dict):
            raise ValueError(
                f"{module_name}: upstream inputs missing."
            )

        if set(received) != set(required):
            raise ValueError(
                f"{module_name}: expected {required}, "
                f"received {sorted(received)}"
            )

        output["consumed_upstream_modules"] = sorted(
            received
        )

    # Deliberate PP1 review demonstration:
    # Version 1 has an incomplete relationship list.
    # Version 2 and later restore the complete list.
    if module_name == "database_design" and version == 1:
        output["relationships"] = (
            output["relationships"][:1]
        )
        output["demo_issue"] = (
            "Missing members-to-borrowing_records "
            "relationship. Reviewer feedback is needed."
        )
        output["schema_validation"] = {
            "status": "MOCK_INCOMPLETE",
            "note": "One relationship deliberately omitted.",
        }

    elif module_name == "database_design":
        output["demo_issue"] = None
        output["schema_validation"] = {
            "status": "MOCK_EXAMPLE",
            "note": (
                "Both demonstration relationships included; "
                "not executed against PostgreSQL."
            ),
        }

    return {
        "project_id": project.project_id,
        "module_name": module_name,
        "version": version,
        "mock": True,
        "source_requirements": [
            req.requirement_id
            for req in project.requirements
        ],
        "input_artifacts": sorted(
            approved_outputs.keys()
        ),
        "data": output,
    }
