import re

from .schemas import APIOperation

from shared.models.common import (
    ValidationIssue,
)


class RefinementEngine:

    """
    Deterministic refinement stage for generated API operations.

    This engine performs only safe structural corrections.

    It does NOT invent:
    - database fields
    - requirements
    - architecture elements
    - business rules
    - path parameters
    - HTTP semantics

    Semantic problems that cannot be corrected safely are left
    unchanged so that final validation can still report them.
    """

    ALLOWED_METHODS = {
        "GET",
        "POST",
        "PUT",
        "PATCH",
        "DELETE",
    }


   
    # PUBLIC METHOD
  

    def refine(
        self,
        operations: list[APIOperation],
        issues: list[ValidationIssue],
    ) -> list[APIOperation]:

        refined_operations: list[
            APIOperation
        ] = []


        # Keep the issues parameter because refinement is
        # conceptually driven by validation findings.
        #
        # In this first deterministic implementation,
        # corrections are based on safe structural rules
        # rather than parsing issue-message text.
        
        _ = issues


        for operation in operations:

            # Work on a deep copy so that the original
            # candidate generated by the LLM/baseline is
            # not modified in place.
            refined_operation = (
                operation.model_copy(
                    deep=True
                )
            )


            # 1. NORMALIZE HTTP METHOD
         

            refined_operation.method = (
                self._normalize_http_method(
                    refined_operation.method
                )
            )


           
            # 2. NORMALIZE API PATH
         

            refined_operation.path = (
                self._normalize_path(
                    refined_operation.path
                )
            )


            refined_operations.append(
                refined_operation
            )


        return refined_operations


    
    # HTTP METHOD NORMALIZATION
  

    def _normalize_http_method(
        self,
        method: str,
    ) -> str:

        """
        Normalize HTTP method casing.

        Example:

            post
            ->
            POST

        If the method itself is unsupported, the method is
        preserved after upper-casing so that the validator
        can still reject it.

        Example:

            trace
            ->
            TRACE

        TRACE is still invalid according to the current
        DesignTrace AI allowed method set.
        """

        if not method:

            return method


        normalized_method = (
            method.strip().upper()
        )


        return normalized_method



    # PATH NORMALIZATION


    def _normalize_path(
        self,
        path: str,
    ) -> str:

        """
        Apply only safe structural path corrections.

        Supported deterministic corrections:

        appointments
        ->
        /appointments


        /Medical-Certificates
        ->
        /medical-certificates


        /appointments//{appointment_id}
        ->
        /appointments/{appointment_id}


        Path parameter names are preserved exactly.

        Example:

        /Appointments/{appointment_id}/Cancel

        becomes:

        /appointments/{appointment_id}/cancel
        """

        if not path:

            return path


       
        # Remove accidental leading/trailing whitespace
      

        normalized_path = (
            path.strip()
        )


        # Ensure path starts with /
   

        if not normalized_path.startswith(
            "/"
        ):

            normalized_path = (
                "/"
                + normalized_path
            )



        # Collapse repeated /
        #
        # Example:
        #
        # /appointments//123
        # ->
        # /appointments/123


        normalized_path = re.sub(
            r"/{2,}",
            "/",
            normalized_path,
        )


        # Normalize literal path segments to lowercase.
        #
        # IMPORTANT:
        # Path parameters inside { } are preserved.
    

        segments = (
            normalized_path.split("/")
        )


        normalized_segments = []


        for segment in segments:

            if not segment:

                normalized_segments.append(
                    segment
                )

                continue


            # Preserve valid path parameter
            # names exactly.
            if re.fullmatch(
                r"\{[^{}]+\}",
                segment,
            ):

                normalized_segments.append(
                    segment
                )

                continue


            normalized_segments.append(
                segment.lower()
            )


        normalized_path = "/".join(
            normalized_segments
        )

        # Remove trailing slash except for root /


        if (
            len(normalized_path) > 1
            and normalized_path.endswith("/")
        ):

            normalized_path = (
                normalized_path.rstrip("/")
            )


        return normalized_path