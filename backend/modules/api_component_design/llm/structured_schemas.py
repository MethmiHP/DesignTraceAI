from pydantic import BaseModel, Field
from ..schemas import APIParameter


class APIFieldSpec(BaseModel):
    """
    Represents one request or response field
    generated by the LLM.
    """

    name: str
    type: str


class APIErrorSpec(BaseModel):
    """
    Represents one HTTP error response
    generated by the LLM.
    """

    status_code: str
    message: str


class LLMAPIOperation(BaseModel):
    """
    Gemini-compatible intermediate API operation.

    Lists are used instead of arbitrary dictionaries
    because Gemini Developer API structured output
    does not support JSON Schema additionalProperties.
    """

    operation_id: str
    requirement_id: str
    element_id: str

    method: str
    path: str

    request_fields: list[APIFieldSpec] = Field(
        default_factory=list
    )

    response_fields: list[APIFieldSpec] = Field(
        default_factory=list
    )

    errors: list[APIErrorSpec] = Field(
        default_factory=list
    )
    parameters: list[APIParameter] = Field(default_factory=list)
