"""
DesignTrace AI - Database Design Artifact Generator.

Generates:
1. PostgreSQL SQL schema
2. Mermaid ER diagram
3. SQL and Mermaid artifact files

Supports project-independent structured constraints.
"""

import re
from pathlib import Path


def sql_identifier(name):
    if not isinstance(name, str) or not name:
        raise ValueError("SQL identifier cannot be empty.")

    return '"' + name.replace('"', '""') + '"'


def sql_data_type(data_type):
    if not isinstance(data_type, str):
        raise ValueError("SQL data type must be a string.")

    value = " ".join(data_type.strip().upper().split())

    allowed = {
        "INTEGER",
        "INT",
        "BIGINT",
        "SMALLINT",
        "TEXT",
        "BOOLEAN",
        "DATE",
        "TIME",
        "TIMESTAMP",
        "TIMESTAMPTZ",
        "UUID",
        "JSONB",
        "REAL",
        "DOUBLE PRECISION",
        "SERIAL",
        "BIGSERIAL",
        "NUMERIC",
        "DECIMAL",
    }

    if value in allowed:
        return value

    if re.fullmatch(
        r"(VARCHAR|CHAR|CHARACTER VARYING)"
        r"\s*\(\s*\d+\s*\)",
        value,
    ):
        return value

    if re.fullmatch(
        r"(NUMERIC|DECIMAL)"
        r"\s*\(\s*\d+\s*(,\s*\d+\s*)?\)",
        value,
    ):
        return value

    raise ValueError(
        f"Unsupported PostgreSQL data type: {data_type}"
    )


def generate_sql(
    design,
    constraint_rules=None,
    use_identity=False,
):
    """
    Generate PostgreSQL SQL from an artifact-compatible
    database design dictionary.

    CHECK constraints are generated from structured rules.
    """

    constraint_rules = constraint_rules or {}

    statements = []
    foreign_key_statements = []

    for table in design["tables"]:
        table_name = sql_identifier(table["name"])

        definitions = []
        primary_keys = []

        primary_key_count = sum(
            bool(column["primary_key"])
            for column in table["columns"]
        )

        for column in table["columns"]:
            column_name = sql_identifier(column["name"])
            data_type = sql_data_type(
                column["data_type"]
            )

            definition = (
                f"    {column_name} {data_type}"
            )

            # Optional auto-generated BIGINT primary keys.
            if (
                use_identity
                and column["primary_key"]
                and data_type == "BIGINT"
                and primary_key_count == 1
            ):
                definition += (
                    " GENERATED BY DEFAULT AS IDENTITY"
                )

            if (
                not column["nullable"]
                or column["primary_key"]
            ):
                definition += " NOT NULL"

            expected_unique = any(
                rule.get("table") == table["name"]
                and rule.get("column") == column["name"]
                for rule in constraint_rules.get(
                    "unique", []
                )
            )

            if (
                column["unique"] or expected_unique
            ) and not column["primary_key"]:
                definition += " UNIQUE"

            expected_not_null = any(
                rule.get("table") == table["name"]
                and rule.get("column") == column["name"]
                for rule in constraint_rules.get(
                    "not_null", []
                )
            )

            if (
                expected_not_null
                and "NOT NULL" not in definition
            ):
                definition += " NOT NULL"

            # Generate safe CHECK constraints.
            for rule in constraint_rules.get(
                "checks", []
            ):
                if (
                    rule.get("table") != table["name"]
                    or rule.get("column")
                    != column["name"]
                ):
                    continue

                if "allowed_values" in rule:
                    values = rule["allowed_values"]

                    if not values or len(values) > 100:
                        raise ValueError(
                            "Invalid allowed_values constraint"
                        )

                    quoted_values = [
                        "'" + str(value).replace(
                            "'", "''"
                        ) + "'"
                        for value in values
                    ]

                    definition += (
                        f" CHECK ({column_name} IN "
                        f"({', '.join(quoted_values)}))"
                    )

                else:
                    operator = rule.get("operator")
                    value = rule.get("value")

                    if operator not in (
                        ">",
                        ">=",
                        "<",
                        "<=",
                        "=",
                        "!=",
                    ):
                        raise ValueError(
                            "Unsupported CHECK operator"
                        )

                    if (
                        not isinstance(value, (int, float))
                        or isinstance(value, bool)
                    ):
                        raise ValueError(
                            "CHECK value must be numeric"
                        )

                    definition += (
                        f" CHECK ({column_name} "
                        f"{operator} {value})"
                    )

            definitions.append(definition)

            if column["primary_key"]:
                primary_keys.append(column_name)

        if not primary_keys:
            raise ValueError(
                f"Table {table['name']} "
                f"has no primary key."
            )

        definitions.append(
            "    PRIMARY KEY ("
            + ", ".join(primary_keys)
            + ")"
        )

        statement = (
            f"CREATE TABLE {table_name} (\n"
            + ",\n".join(definitions)
            + "\n);"
        )

        statements.append(statement)

        # Add foreign keys after CREATE TABLE statements.
        for fk in table.get("foreign_keys", []):
            foreign_key_statements.append(
                "ALTER TABLE "
                + table_name
                + " ADD FOREIGN KEY ("
                + sql_identifier(fk["column"])
                + ") REFERENCES "
                + sql_identifier(
                    fk["references_table"]
                )
                + " ("
                + sql_identifier(
                    fk["references_column"]
                )
                + ");"
            )

    return (
        "-- Generated by DesignTrace AI\n"
        "-- PostgreSQL database schema\n\n"
        + "\n\n".join(statements)
        + "\n\n"
        + "\n".join(foreign_key_statements)
        + "\n"
    )


def mermaid_identifier(name):
    result = re.sub(
        r"[^A-Za-z0-9_]",
        "_",
        name,
    )

    if not result:
        result = "unnamed"

    if result[0].isdigit():
        result = "_" + result

    return result


def generate_mermaid_er(design):
    """
    Generate a Mermaid ER diagram from tables
    and foreign key relationships.
    """

    lines = ["erDiagram"]

    names = {
        table["name"]: mermaid_identifier(
            table["name"]
        )
        for table in design["tables"]
    }

    if len(set(names.values())) != len(names):
        raise ValueError(
            "Duplicate Mermaid identifiers."
        )

    for table in design["tables"]:
        table_name = names[table["name"]]

        lines.append(f"    {table_name} {{")

        for column in table["columns"]:
            data_type = mermaid_identifier(
                column["data_type"]
            )

            column_name = mermaid_identifier(
                column["name"]
            )

            markers = []

            if column["primary_key"]:
                markers.append("PK")

            if any(
                fk["column"] == column["name"]
                for fk in table.get(
                    "foreign_keys", []
                )
            ):
                markers.append("FK")

            marker_text = (
                " " + ",".join(markers)
                if markers
                else ""
            )

            lines.append(
                f"        {data_type} "
                f"{column_name}{marker_text}"
            )

        lines.append("    }")

    for table in design["tables"]:
        child = names[table["name"]]

        for fk in table.get("foreign_keys", []):
            parent_name = fk["references_table"]

            if parent_name not in names:
                raise ValueError(
                    f"Unknown referenced table: "
                    f"{parent_name}"
                )

            parent = names[parent_name]

            lines.append(
                f"    {parent} ||--o{{ {child} "
                f": references"
            )

    return "\n".join(lines) + "\n"


def save_artifacts(
    design,
    output_dir,
    base_name="database_design",
    constraint_rules=None,
    use_identity=False,
):
    """
    Save SQL and Mermaid files.
    """

    output_dir = Path(output_dir)

    output_dir.mkdir(
        parents=True,
        exist_ok=True,
    )

    sql_path = (
        output_dir / f"{base_name}.sql"
    )

    er_path = (
        output_dir / f"{base_name}.mmd"
    )

    sql_text = generate_sql(
        design,
        constraint_rules=constraint_rules,
        use_identity=use_identity,
    )

    mermaid_text = generate_mermaid_er(
        design
    )

    sql_path.write_text(
        sql_text,
        encoding="utf-8",
    )

    er_path.write_text(
        mermaid_text,
        encoding="utf-8",
    )

    return {
        "sql_file": str(sql_path),
        "er_diagram_file": str(er_path),
    }