"""
Validate SQL generated by the DesignTrace AI artifact generator.

This validator is project-independent.

Supported:
- UNIQUE
- NOT NULL
- CHECK
- FOREIGN KEY
- PRIMARY KEY
- IDENTITY

"""

import re
from decimal import Decimal


def quote_identifier(value):
    return '"' + str(value).replace('"', '""') + '"'


def compact_sql(value):
    return re.sub(r"\s+", "", str(value)).lower()


def get_table_body(sql_text, table_name):
    quoted_name = re.escape(
        quote_identifier(table_name)
    )

    pattern = (
        r"CREATE\s+TABLE\s+"
        + quoted_name
        + r"\s*\("
    )

    match = re.search(
        pattern,
        sql_text,
        flags=re.IGNORECASE,
    )

    if not match:
        return ""

    # Works for CREATE TABLE statements emitted by
    # DesignTrace AI's artifact generator.
    end = sql_text.find(");", match.end())

    if end == -1:
        return ""

    return sql_text[match.end():end]


def validate_sql_constraints(sql_text, rules):
    passed_checks = []
    errors = []
    checked_rules = 0

    def record(success, message):
        nonlocal checked_rules

        checked_rules += 1

        if success:
            passed_checks.append(message)
        else:
            errors.append(message)

    # UNIQUE
    for rule in rules.get("unique", []):
        table = rule["table"]
        column = rule["column"]

        body = get_table_body(sql_text, table)

        pattern = (
            re.escape(quote_identifier(column))
            + r"[^,\n]*\bUNIQUE\b"
        )

        success = bool(
            re.search(pattern, body, re.IGNORECASE)
        )

        record(
            success,
            f"UNIQUE: {table}.{column}",
        )

    # NOT NULL
    for rule in rules.get("not_null", []):
        table = rule["table"]
        column = rule["column"]

        body = get_table_body(sql_text, table)

        pattern = (
            re.escape(quote_identifier(column))
            + r"\s+[^,\n]+?\s+NOT\s+NULL\b"
        )

        success = bool(
            re.search(pattern, body, re.IGNORECASE)
        )

        record(
            success,
            f"NOT NULL: {table}.{column}",
        )

    # CHECK
    for rule in rules.get("checks", []):
        table = rule["table"]
        column = rule["column"]

        body = compact_sql(
            get_table_body(sql_text, table)
        )

        if "allowed_values" in rule:
            values = ", ".join(
                "'" + str(value).replace("'", "''") + "'"
                for value in rule["allowed_values"]
            )

            expected = (
                f"CHECK ({quote_identifier(column)} "
                f"IN ({values}))"
            )

        else:
            expected = (
                f"CHECK ({quote_identifier(column)} "
                f"{rule['operator']} {rule['value']})"
            )

        if "allowed_values" in rule:
            success = compact_sql(expected) in body
        else:
            # Numeric equivalents such as 0 and 0.0 are the same CHECK.
            check_pattern = (
                r"CHECK\s*\(\s*"
                + re.escape(quote_identifier(column))
                + r"\s*" + re.escape(str(rule["operator"]))
                + r"\s*(-?\d+(?:\.\d+)?)\s*\)"
            )
            success = any(
                Decimal(match.group(1)) == Decimal(str(rule["value"]))
                for match in re.finditer(check_pattern, get_table_body(sql_text, table), re.IGNORECASE)
            )

        record(
            success,
            f"CHECK: {table}.{column} "
            f"({expected})",
        )

    # FOREIGN KEY
    for rule in rules.get("foreign_keys", []):
        table = rule["table"]
        column = rule["column"]
        target_table = rule["references_table"]
        target_column = rule["references_column"]

        expected = (
            f"ALTER TABLE {quote_identifier(table)} "
            f"ADD FOREIGN KEY "
            f"({quote_identifier(column)}) "
            f"REFERENCES {quote_identifier(target_table)} "
            f"({quote_identifier(target_column)})"
        )

        success = (
            compact_sql(expected)
            in compact_sql(sql_text)
        )

        record(
            success,
            f"FOREIGN KEY: {table}.{column} -> "
            f"{target_table}.{target_column}",
        )

    # PRIMARY KEY
    for rule in rules.get("primary_keys", []):
        table = rule["table"]

        columns = rule.get("columns")

        if columns is None:
            columns = [rule["column"]]

        quoted_columns = ", ".join(
            quote_identifier(column)
            for column in columns
        )

        expected = (
            f"PRIMARY KEY ({quoted_columns})"
        )

        body = compact_sql(
            get_table_body(sql_text, table)
        )

        success = compact_sql(expected) in body

        record(
            success,
            f"PRIMARY KEY: {table} {columns}",
        )

    # IDENTITY
    for rule in rules.get("identity", []):
        table = rule["table"]
        column = rule["column"]

        body = get_table_body(sql_text, table)

        pattern = (
            re.escape(quote_identifier(column))
            + r"\s+BIGINT\s+"
            + r"GENERATED BY DEFAULT AS IDENTITY"
        )

        success = bool(
            re.search(pattern, body, re.IGNORECASE)
        )

        record(
            success,
            f"IDENTITY: {table}.{column}",
        )

    if checked_rules == 0:
        errors.append(
            "No constraints were checked. "
            "Constraint completeness is not verified."
        )

    return {
        "valid": len(errors) == 0,
        "passed_checks": passed_checks,
        "errors": errors,
        "checked_rules": checked_rules,
    }