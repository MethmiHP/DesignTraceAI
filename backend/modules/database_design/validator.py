"""
DesignTrace AI - Database Design Validator
==========================================

Purpose:
    This file performs deterministic rule-based validation on
    database designs generated by the Database Design Module.

Why validation is needed:
    AI-generated database designs may contain problems such as:

        - Tables without primary keys
        - Foreign keys referencing missing tables
        - Foreign keys referencing missing columns
        - Invalid relationships
        - Unsupported data types
        - Missing requirement mappings

Current Rules:
    DB-R01: Every generated table must contain at least one primary key.
    DB-R02: Every foreign key must reference an existing table and an existing column.
    DB-R03 - Relationship validation
    DB-R04 - Data type validation
    DB-R05 - Constraint validation
    DB-R06 - Requirement coverage validation
"""

from pydantic import BaseModel, Field

from shared.models.database import DatabaseDesign
from shared.models.project import Requirement


# VALIDATION RESULT MODELS

class ValidationIssue(BaseModel):
    """
    Represents one problem discovered by a database validation rule.
    """

    rule_id: str

    severity: str

    message: str

    table_name: str | None = None

    column_name: str | None = None


class DatabaseValidationResult(BaseModel):
    """
    Represents the complete validation result for one database design.
    """

    passed: bool

    issues: list[ValidationIssue] = Field(
        default_factory=list
    )


# DB-R01
# EVERY TABLE MUST HAVE A PRIMARY KEY

def validate_primary_keys(
    design: DatabaseDesign,
) -> list[ValidationIssue]:
    """
    DB-R01:
    Check that every generated table contains at least one
    primary-key column.
    """

    issues = []

    for table in design.tables:

        has_primary_key = any(
            column.primary_key
            for column in table.columns
        )

        if not has_primary_key:

            issues.append(
                ValidationIssue(
                    rule_id="DB-R01",
                    severity="ERROR",
                    table_name=table.table_name,
                    message=(
                        f"Table '{table.table_name}' "
                        "does not contain a primary key."
                    ),
                )
            )

    return issues

# DB-R02
# FOREIGN KEYS MUST REFERENCE VALID TABLES AND COLUMNS

def validate_foreign_keys(
    design: DatabaseDesign,
) -> list[ValidationIssue]:
    """
    DB-R02:
    Check that every foreign key references:

        1. An existing table.
        2. An existing column inside that table.
    """

    issues = []

    table_lookup = {
        table.table_name: table
        for table in design.tables
    }

    for table in design.tables:

        for column in table.columns:

            foreign_key = column.foreign_key

            # This column is not a foreign key.
            if foreign_key is None:
                continue

            referenced_table = table_lookup.get(
                foreign_key.table
            )

            if referenced_table is None:

                issues.append(
                    ValidationIssue(
                        rule_id="DB-R02",
                        severity="ERROR",
                        table_name=table.table_name,
                        column_name=column.name,
                        message=(
                            f"Foreign key "
                            f"'{table.table_name}.{column.name}' "
                            f"references missing table "
                            f"'{foreign_key.table}'."
                        ),
                    )
                )

                continue

            # Check whether referenced column exists.

            referenced_column_exists = any(
                referenced_column.name == foreign_key.column
                for referenced_column in referenced_table.columns
            )

            if not referenced_column_exists:

                issues.append(
                    ValidationIssue(
                        rule_id="DB-R02",
                        severity="ERROR",
                        table_name=table.table_name,
                        column_name=column.name,
                        message=(
                            f"Foreign key "
                            f"'{table.table_name}.{column.name}' "
                            f"references missing column "
                            f"'{foreign_key.table}."
                            f"{foreign_key.column}'."
                        ),
                    )
                )

    return issues

# DB-R03: RELATIONSHIP VALIDATION

def validate_relationships(
    design: DatabaseDesign,
) -> list[ValidationIssue]:
    """
    DB-R03:
    Check that each relationship:
        1. Uses existing tables.
        2. Uses a valid relationship type.
        3. References an existing foreign-key column.
        4. Connects that foreign key to the related table.
    """

    issues = []

    table_lookup = {
        table.table_name: table
        for table in design.tables
    }

    allowed_types = {
        "one-to-one",
        "one-to-many",
        "many-to-one",
        "many-to-many",
    }

    for relationship in design.relationships:

        for table_name in [
            relationship.from_table,
            relationship.to_table,
        ]:
            if table_name not in table_lookup:
                issues.append(
                    ValidationIssue(
                        rule_id="DB-R03",
                        severity="ERROR",
                        table_name=table_name,
                        message=(
                            f"Relationship "
                            f"'{relationship.relationship_id}' "
                            f"references missing table '{table_name}'."
                        ),
                    )
                )

        if relationship.relationship_type not in allowed_types:
            issues.append(
                ValidationIssue(
                    rule_id="DB-R03",
                    severity="ERROR",
                    message=(
                        f"Relationship "
                        f"'{relationship.relationship_id}' "
                        "has an unsupported relationship type."
                    ),
                )
            )

        parts = relationship.foreign_key.split(".")

        if len(parts) != 2 or not all(parts):
            issues.append(
                ValidationIssue(
                    rule_id="DB-R03",
                    severity="ERROR",
                    message=(
                        f"Relationship "
                        f"'{relationship.relationship_id}' "
                        "has an invalid foreign-key format."
                    ),
                )
            )
            continue

        fk_table_name, fk_column_name = parts
        fk_table = table_lookup.get(fk_table_name)

        if fk_table is None:
            continue

        fk_column = next(
            (
                column
                for column in fk_table.columns
                if column.name == fk_column_name
            ),
            None,
        )

        if fk_column is None or fk_column.foreign_key is None:
            issues.append(
                ValidationIssue(
                    rule_id="DB-R03",
                    severity="ERROR",
                    table_name=fk_table_name,
                    column_name=fk_column_name,
                    message=(
                        f"Relationship "
                        f"'{relationship.relationship_id}' "
                        "does not reference a valid foreign-key column."
                    ),
                )
            )
            continue

        if fk_table_name == relationship.to_table:
            expected_reference = relationship.from_table
        elif fk_table_name == relationship.from_table:
            expected_reference = relationship.to_table
        else:
            issues.append(
                ValidationIssue(
                    rule_id="DB-R03",
                    severity="ERROR",
                    table_name=fk_table_name,
                    column_name=fk_column_name,
                    message="Relationship foreign key belongs to an unrelated table.",
                )
            )
            continue

        if fk_column.foreign_key.table != expected_reference:
            issues.append(
                ValidationIssue(
                    rule_id="DB-R03",
                    severity="ERROR",
                    table_name=fk_table_name,
                    column_name=fk_column_name,
                    message=(
                        f"Relationship "
                        f"'{relationship.relationship_id}' "
                        "foreign key points to the wrong table."
                    ),
                )
            )

    return issues

# DB-R04: DATA TYPE VALIDATION

import re


def validate_data_types(
    design: DatabaseDesign,
) -> list[ValidationIssue]:
    """
    DB-R04:
    Check whether columns use supported PostgreSQL-style
    data type names.

    This is an initial allowlist, not a complete SQL type parser.
    """

    issues = []

    allowed_type_pattern = re.compile(
        r"^(?:"
        r"SMALLINT|INTEGER|INT|BIGINT|"
        r"BOOLEAN|BOOL|TEXT|DATE|"
        r"TIMESTAMP(?: WITH(?:OUT)? TIME ZONE)?|"
        r"TIMESTAMPTZ|TIME|"
        r"UUID|JSON|JSONB|BYTEA|"
        r"REAL|DOUBLE PRECISION|"
        r"VARCHAR\([1-9][0-9]*\)|"
        r"CHAR\([1-9][0-9]*\)|"
        r"NUMERIC\([1-9][0-9]*(?:,[0-9]+)?\)|"
        r"DECIMAL\([1-9][0-9]*(?:,[0-9]+)?\)"
        r")$",
        re.IGNORECASE,
    )

    for table in design.tables:
        for column in table.columns:

            data_type = column.data_type.strip()

            if not allowed_type_pattern.fullmatch(data_type):
                issues.append(
                    ValidationIssue(
                        rule_id="DB-R04",
                        severity="ERROR",
                        table_name=table.table_name,
                        column_name=column.name,
                        message=(
                            f"Column '{table.table_name}.{column.name}' "
                            f"has unsupported data type '{data_type}'."
                        ),
                    )
                )

    return issues


# DB-R06: REQUIREMENT-TO-DATABASE COVERAGE VALIDATION

def validate_requirement_coverage(
    design: DatabaseDesign,
    requirements: list[Requirement],
) -> list[ValidationIssue]:
    """
    DB-R06:
    Check whether every database-relevant requirement is linked
    to at least one generated database table, column, or relationship.

    This checks mapping coverage, not whether the design fully
    satisfies the requirement.
    """

    issues = []

    mapped_requirement_ids = set()

    for table in design.tables:
        mapped_requirement_ids.update(
            table.source_requirement_ids
        )

        for column in table.columns:
            mapped_requirement_ids.update(
                column.source_requirement_ids
            )

    for relationship in design.relationships:
        mapped_requirement_ids.update(
            relationship.source_requirement_ids
        )

    for requirement in requirements:

        if not requirement.database_relevant:
            continue

        if requirement.requirement_id not in mapped_requirement_ids:
            issues.append(
                ValidationIssue(
                    rule_id="DB-R06",
                    severity="ERROR",
                    message=(
                        f"Database-relevant requirement "
                        f"'{requirement.requirement_id}' "
                        "has no database element mapping."
                    ),
                )
            )

    return issues

# COMPLETE DATABASE VALIDATION

def validate_database_design(
    design: DatabaseDesign,
    requirements: list[Requirement] | None = None,
) -> DatabaseValidationResult:
    """
    Run database validation rules DB-R01 to DB-R04.

    DB-R06 is also executed when requirements are provided.

    Passing without requirements does not mean that
    requirement coverage has been checked.
    """

    issues = []

    # Existing structural validation rules.
    issues.extend(validate_primary_keys(design))
    issues.extend(validate_foreign_keys(design))
    issues.extend(validate_relationships(design))
    issues.extend(validate_data_types(design))

    # Requirement coverage validation.
    if requirements is not None:
        issues.extend(
            validate_requirement_coverage(
                design,
                requirements,
            )
        )

    return DatabaseValidationResult(
        passed=not any(
            issue.severity == "ERROR"
            for issue in issues
        ),
        issues=issues,
    )
